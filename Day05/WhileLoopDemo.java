public class WhileLoopDemo {
    public static void main(String[] args) {
        int i = 1;
        System.out.println("Numbers from 1 to 5:");
        while (i <= 5) {
            System.out.println(i);
            i++;
        }
        int even = 2;
        System.out.println("\nEven Numbers:");
        while (even <= 20) {
            System.out.println(even);
            even += 2;
        }
    }
}